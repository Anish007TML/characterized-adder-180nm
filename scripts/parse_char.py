#!/usr/bin/env python3
"""
parse_char.py -- turn T-Spice .measure results into
  1) char/char_table.csv      every arc at every (slew, load) point
  2) char/adder_cells.lib     Liberty-style NLDM tables (delay vs slew x load)
  3) rtl/fa_timing.vh         Verilog `define delays, back-annotated into the
                              cell models' specify blocks

Works with any text that has lines like   name = value   (the T-Spice .out
file, an HSPICE .mt0 dump, or an ngspice log). Values may use e-notation or
SI suffixes (123.4p).

Usage:
  python3 parse_char.py fa_char.out [--points char_points.json]
                        [--nominal-slew 1 --nominal-load 1] [--root ..]
"""
import argparse
import csv
import json
import re
from pathlib import Path

ap = argparse.ArgumentParser()
ap.add_argument("results", help="T-Spice .out file (or any log with name = value lines)")
ap.add_argument("--points", default="char_points.json")
ap.add_argument("--nominal-slew", type=int, default=None, help="grid index used for Verilog delays (default: middle)")
ap.add_argument("--nominal-load", type=int, default=None)
ap.add_argument("--root", default="..", help="project root (where rtl/ and char/ live)")
args = ap.parse_args()

pts = json.loads(Path(args.points).read_text())
slews, loads = pts["slews_s"], pts["loads_f"]
NS, NL = len(slews), len(loads)
si_ = args.nominal_slew if args.nominal_slew is not None else NS // 2
li_ = args.nominal_load if args.nominal_load is not None else NL // 2

SI = {"f": 1e-15, "p": 1e-12, "n": 1e-9, "u": 1e-6, "m": 1e-3}
num = r"[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?[fpnum]?"
pat = re.compile(rf"^\s*([A-Za-z_][\w]*)\s*[=:]\s*({num})(?![\w.])", re.M)


def to_float(s):
    s = s.strip()
    return float(s[:-1]) * SI[s[-1]] if s[-1] in SI else float(s)


meas = {}
for name, val in pat.findall(Path(args.results).read_text(errors="ignore")):
    meas[name.lower()] = to_float(val)

ARCS = ["fa_co_r", "fa_co_f", "fa_s_r", "fa_s_f", "core_cob_r", "core_cob_f",
        "core_sb_r", "core_sb_f", "inv_r", "inv_f", "mux_r", "mux_f",
        "fa_co_tr", "fa_co_tf", "fa_iavg"]

table, missing = {}, []
for arc in ARCS:
    grid = [[None] * NL for _ in range(NS)]
    for i in range(NS):
        for j in range(NL):
            key = f"{arc}_s{i}_l{j}"
            if key in meas:
                grid[i][j] = meas[key]
            else:
                missing.append(key)
    table[arc] = grid

if missing:
    print(f"WARNING: {len(missing)} measurements not found, e.g. {missing[:4]}")
    print("Check the simulation finished and that the file you passed holds the .measure results.")

root = Path(args.root)
(root / "char").mkdir(exist_ok=True)

# ---------- 1) CSV ----------
with open(root / "char" / "char_table.csv", "w", newline="") as f:
    wr = csv.writer(f)
    wr.writerow(["arc", "input_slew_ps", "load_fF", "value", "unit"])
    for arc in ARCS:
        for i in range(NS):
            for j in range(NL):
                v = table[arc][i][j]
                if v is None:
                    continue
                if arc == "fa_iavg":
                    wr.writerow(["fa_avg_power", slews[i] * 1e12, loads[j] * 1e15,
                                 f"{abs(v) * pts['vdd'] * 1e6:.3f}", "uW"])
                else:
                    wr.writerow([arc, slews[i] * 1e12, loads[j] * 1e15, f"{v * 1e12:.2f}", "ps"])

# ---------- 2) Liberty-style NLDM ----------
def lib_table(kind, arc):
    rows = []
    for i in range(NS):
        vals = ", ".join(f"{(table[arc][i][j] or 0) * 1e9:.5f}" for j in range(NL))
        rows.append(f'"{vals}"')
    body = ", \\\n            ".join(rows)
    return (f"        {kind} (delay_template_{NS}x{NL}) {{\n"
            f"          values ( {body} );\n        }}\n")


def lib_arc(pin_from, rise_arc, fall_arc, sense):
    return (f"      timing () {{\n        related_pin : \"{pin_from}\";\n"
            f"        timing_sense : {sense};\n"
            + lib_table("cell_rise", rise_arc) + lib_table("cell_fall", fall_arc)
            + "      }\n")


idx1 = ", ".join(f"{s * 1e9:.4f}" for s in slews)
idx2 = ", ".join(f"{c * 1e12:.4f}" for c in loads)
lib = [f"/* adder_cells.lib -- generated by parse_char.py from {Path(args.results).name}",
       " * Times in ns, capacitance in pF. Arcs characterized with a=1, b=0 (propagate). */",
       "library (adder_cells) {",
       "  time_unit : \"1ns\";  capacitive_load_unit (1, pf);  voltage_unit : \"1V\";",
       f"  nom_voltage : {pts['vdd']};",
       f"  lu_table_template (delay_template_{NS}x{NL}) {{",
       "    variable_1 : input_net_transition;  variable_2 : total_output_net_capacitance;",
       f"    index_1 (\"{idx1}\");  index_2 (\"{idx2}\");", "  }",
       "  cell (FA_MIRROR28) {",
       "    pin (co) { direction : output;",
       lib_arc("ci", "fa_co_r", "fa_co_f", "positive_unate"), "    }",
       "    pin (s) { direction : output;",
       lib_arc("ci", "fa_s_r", "fa_s_f", "negative_unate"), "    }", "  }",
       "  cell (FA_CORE24) {",
       "    pin (cob) { direction : output;",
       lib_arc("ci", "core_cob_r", "core_cob_f", "negative_unate"), "    }",
       "    pin (sb) { direction : output;",
       lib_arc("ci", "core_sb_r", "core_sb_f", "positive_unate"), "    }", "  }",
       "  cell (INV) {", "    pin (out) { direction : output;",
       lib_arc("in", "inv_r", "inv_f", "negative_unate"), "    }", "  }",
       "  cell (MUX2_TG) {", "    pin (y) { direction : output;",
       lib_arc("sel", "mux_r", "mux_f", "positive_unate"), "    }", "  }",
       "}"]
(root / "char" / "adder_cells.lib").write_text("\n".join(lib) + "\n")

# ---------- 3) Verilog delays at the nominal point ----------
def ns(arc):
    v = table[arc][si_][li_]
    return f"{(v if v is not None else 0) * 1e9:.4f}"


vh = f"""// fa_timing.vh -- GENERATED by scripts/parse_char.py from {Path(args.results).name}
// Nominal point: input slew = {slews[si_] * 1e12:g} ps, load = {loads[li_] * 1e15:g} fF, VDD = {pts['vdd']} V
// Units: ns (testbench uses `timescale 1ns/1ps). Re-run the script to update.
`define T_FA_CO_R   {ns('fa_co_r')}
`define T_FA_CO_F   {ns('fa_co_f')}
`define T_FA_S_R    {ns('fa_s_r')}
`define T_FA_S_F    {ns('fa_s_f')}
`define T_CORE_CO_R {ns('core_cob_r')}
`define T_CORE_CO_F {ns('core_cob_f')}
`define T_CORE_S_R  {ns('core_sb_r')}
`define T_CORE_S_F  {ns('core_sb_f')}
`define T_INV_R     {ns('inv_r')}
`define T_INV_F     {ns('inv_f')}
`define T_MUX_R     {ns('mux_r')}
`define T_MUX_F     {ns('mux_f')}
"""
(root / "rtl" / "fa_timing.vh").write_text(vh)

# ---------- console summary ----------
def ps(arc, i=si_, j=li_):
    v = table[arc][i][j]
    return "  --  " if v is None else f"{v * 1e12:7.1f}"


print(f"\nNominal point: slew {slews[si_] * 1e12:g} ps, load {loads[li_] * 1e15:g} fF")
print("arc                 rise(ps)  fall(ps)")
for name, r, f_ in [("FA28  ci->co", "fa_co_r", "fa_co_f"), ("FA28  ci->s", "fa_s_r", "fa_s_f"),
                    ("CORE  ci->cob", "core_cob_r", "core_cob_f"), ("CORE  ci->sb", "core_sb_r", "core_sb_f"),
                    ("INV   in->out", "inv_r", "inv_f"), ("MUX   sel->y", "mux_r", "mux_f")]:
    print(f"{name:18s} {ps(r)}   {ps(f_)}")
p = table["fa_iavg"][si_][li_]
if p is not None:
    print(f"FA28 average power (1 toggle pair per {pts['period_s'] * 1e9:g} ns): {abs(p) * pts['vdd'] * 1e6:.2f} uW")
print("\nci->co rise delay (ps) vs slew (rows) x load (cols):")
print("            " + "".join(f"{c * 1e15:>8g}fF" for c in loads))
for i in range(NS):
    print(f"{slews[i] * 1e12:>8g}ps  " + "".join(f"{ps('fa_co_r', i, j):>10s}" for j in range(NL)))
print(f"\nwrote {root / 'char/char_table.csv'}, {root / 'char/adder_cells.lib'}, {root / 'rtl/fa_timing.vh'}")
