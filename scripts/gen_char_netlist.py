#!/usr/bin/env python3
"""
gen_char_netlist.py -- build ONE T-Spice netlist that characterizes the cells
over a grid of input slew x output load (like a standard-cell library does).

Instead of relying on simulator-specific sweep syntax, the script places one
copy of each cell per (slew, load) point, each with its own input ramp and
load capacitor, and writes one .measure line per arc. Any SPICE that supports
.measure trig/targ (T-Spice, HSPICE, ngspice) can run it in a single pass.

Arcs measured (A=1, B=0, so the cell is in "propagate" mode and the carry
input ripples straight through -- the critical path of a ripple adder):
  FA_MIRROR28 : ci -> co (rise/fall), ci -> s (rise/fall), co transition, avg supply current
  FA_CORE24   : ci -> cob (rise/fall)   [used by the inverting-chain adder]
  FA_CORE24   : ci -> sb  (rise/fall)
  INV         : in -> out (rise/fall)   [polarity restore]
  MUX2_TG     : sel -> y (rise/fall)    [used by the carry-select adder]

Usage:
  python3 gen_char_netlist.py --lib "demo_models_level1.lib"            # .include a file
  python3 gen_char_netlist.py --lib "C:/models/180nm.lib" --corner TT   # .lib file corner
Outputs: fa_char.sp (netlist) and char_points.json (grid, read by parse_char.py)
"""
import argparse
import json
import re
from pathlib import Path

ap = argparse.ArgumentParser()
ap.add_argument("--cells", default="fa_mirror28.sp", help="subcircuit file")
ap.add_argument("--lib", default="demo_models_level1.lib", help="model file")
ap.add_argument("--corner", default=None, help="corner name if the model file uses .lib sections (e.g. TT)")
ap.add_argument("--nmos", default="nch", help="NMOS model name in your library")
ap.add_argument("--pmos", default="pch", help="PMOS model name in your library")
ap.add_argument("--vdd", type=float, default=1.8)
ap.add_argument("--slews", default="20p,50p,100p", help="input 0-100%% ramp times")
ap.add_argument("--loads", default="2f,5f,10f", help="output load capacitances")
ap.add_argument("--out", default="fa_char.sp")
args = ap.parse_args()

SI = {"f": 1e-15, "p": 1e-12, "n": 1e-9, "u": 1e-6, "m": 1e-3}


def si(x):
    x = x.strip().lower()
    return float(x[:-1]) * SI[x[-1]] if x[-1] in SI else float(x)


slews = [s.strip() for s in args.slews.split(",")]
loads = [c.strip() for c in args.loads.split(",")]
vdd, half = args.vdd, args.vdd / 2
lo, hi = 0.1 * vdd, 0.9 * vdd

# Copy the subcircuits inline, renaming the model names if needed.
cells = Path(args.cells).read_text()
if args.nmos != "nch":
    cells = re.sub(r"\bnch\b", args.nmos, cells)
if args.pmos != "pch":
    cells = re.sub(r"\bpch\b", args.pmos, cells)

L = []
w = L.append
w("* fa_char.sp -- generated by gen_char_netlist.py, do not edit by hand")
w(f"* grid: slews={slews} loads={loads} vdd={vdd}")
w(f'.lib "{args.lib}" {args.corner}' if args.corner else f'.include "{args.lib}"')
w(cells)
w(f"Va a 0 DC {vdd}")
w("Vb b 0 DC 0")
w(f"Vm1 one 0 DC {vdd}")
w("Vm0 zero 0 DC 0")
w(f"Vdd vdd 0 DC {vdd}")

period = 4e-9
for i, sl in enumerate(slews):
    for j, cl in enumerate(loads):
        k = f"s{i}_l{j}"
        # One input ramp per point: rises at 1 ns, falls at 3 ns.
        pw = period / 2 - si(sl)
        w(f"\n* ---- point {k}: slew={sl} load={cl} ----")
        w(f"Vin_{k} in_{k} 0 PULSE(0 {vdd} 1n {sl} {sl} {pw:.4e} {period:.0e})")
        # Full 28T cell with its own supply so its current can be measured
        w(f"Vdd_{k} vdd_{k} 0 DC {vdd}")
        w(f"Xfa_{k} a b in_{k} co_{k} s_{k} cob_{k} sb_{k} vdd_{k} 0 FA_MIRROR28")
        w(f"Cco_{k} co_{k} 0 {cl}")
        w(f"Cs_{k} s_{k} 0 {cl}")
        # 24T core alone, cob loaded directly (as in the inverting chain)
        w(f"Xcore_{k} a b in_{k} kcob_{k} ksb_{k} vdd 0 FA_CORE24")
        w(f"Ccob_{k} kcob_{k} 0 {cl}")
        w(f"Cksb_{k} ksb_{k} 0 {cl}")
        # Plain inverter (restores polarity in the inverting chain)
        w(f"Xinv_{k} in_{k} iv_{k} vdd 0 INV")
        w(f"Civ_{k} iv_{k} 0 {cl}")
        # Mux, select driven by the ramp, d0=0 d1=1 so y follows sel
        w(f"Xmux_{k} zero one in_{k} y_{k} vdd 0 MUX2_TG")
        w(f"Cy_{k} y_{k} 0 {cl}")
        m = lambda name, out, edge_in, edge_out: w(
            f".measure tran {name}_{k} trig v(in_{k}) val={half:g} {edge_in}=1 "
            f"targ v({out}_{k}) val={half:g} {edge_out}=1")
        m("fa_co_r", "co", "rise", "rise")      # ci up   -> co up
        m("fa_co_f", "co", "fall", "fall")      # ci down -> co down
        m("fa_s_f", "s", "rise", "fall")        # ci up   -> s down (a^b=1)
        m("fa_s_r", "s", "fall", "rise")        # ci down -> s up
        m("core_cob_f", "kcob", "rise", "fall")  # ci up  -> cob down
        m("core_cob_r", "kcob", "fall", "rise")  # ci down -> cob up
        m("core_sb_r", "ksb", "rise", "rise")    # ci up  -> sb up
        m("core_sb_f", "ksb", "fall", "fall")    # ci down -> sb down
        m("inv_f", "iv", "rise", "fall")
        m("inv_r", "iv", "fall", "rise")
        m("mux_r", "y", "rise", "rise")
        m("mux_f", "y", "fall", "fall")
        w(f".measure tran fa_co_tr_{k} trig v(co_{k}) val={lo:g} rise=1 targ v(co_{k}) val={hi:g} rise=1")
        w(f".measure tran fa_co_tf_{k} trig v(co_{k}) val={hi:g} fall=1 targ v(co_{k}) val={lo:g} fall=1")
        w(f".measure tran fa_iavg_{k} avg i(Vdd_{k}) from=0.5n to=4.5n")

w("\n.tran 1p 5n")
w(".end")
Path(args.out).write_text("\n".join(L) + "\n")

points = {"vdd": vdd, "slews": slews, "loads": loads,
          "slews_s": [si(s) for s in slews], "loads_f": [si(c) for c in loads],
          "period_s": period}
Path("char_points.json").write_text(json.dumps(points, indent=2))
print(f"wrote {args.out} ({len(slews)}x{len(loads)} points) and char_points.json")
print("next: run it in T-Spice, then: python3 parse_char.py <the .out / log file>")
